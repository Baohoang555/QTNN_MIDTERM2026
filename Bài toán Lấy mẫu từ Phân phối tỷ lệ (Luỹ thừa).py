import numpy as np
import matplotlib.pyplot as plt
import matplotlib.gridspec as gridspec
from scipy.special import zeta   # dùng tính hằng số chuẩn hóa


# 1. Phân phối đích (discrete power-law)

def pi_unnorm(i, s=1.5):
    """Trọng số chưa chuẩn hóa: π̃_i = i^(-s)"""
    return i ** (-s)


def exact_prob(i_max, s=1.5):
    """
    Tính xác suất chính xác bằng cách chuẩn hóa thủ công.
    C = Σ_{i=1}^{∞} i^{-s}  ≈  ζ(s)  (hàm Riemann zeta)
    """
    C = zeta(s, 1)          # ζ(s) = Σ_{k=1}^∞ k^{-s}
    probs = {i: i**(-s) / C for i in range(1, i_max + 1)}
    return probs


# 2. Thuật toán Metropolis-Hastings (rời rạc)

def mh_discrete_powerlaw(n_steps, s=1.5, seed=42):
    """
    Metropolis-Hastings lấy mẫu từ π_i ∝ i^(-s), i = 1,2,3,...

    Proposal: symmetric random walk trên Z+ với reflecting boundary tại 1
        - Tại i = 1: luôn đề xuất j = 2  (boundary)
        - Tại i > 1: đề xuất j = i-1 hoặc j = i+1, mỗi cái xác suất 1/2

    Vì proposal đối xứng (ngoại trừ tại biên), ta dùng
    Metropolis acceptance (trường hợp đặc biệt của MH):
        a(i, j) = min(1, π_j / π_i) = min(1, (i/j)^s)

    Tuy nhiên tại biên i=1, proposal KHÔNG đối xứng:
        T_{1,2} = 1  nhưng  T_{2,1} = 1/2
    Nên phải dùng Hastings correction đầy đủ:
        a(1,2) = min(1, π_2 * T_{2,1} / (π_1 * T_{1,2}))
               = min(1, 2^{-s} * (1/2) / (1^{-s} * 1))
               = min(1, (1/2)^{s+1})
               = (1/2)^{s+1}          [vì s > 0 nên tỷ số < 1]
    """
    np.random.seed(seed)
    chain    = np.zeros(n_steps, dtype=int)
    accepted = 0
    x        = 1       # bắt đầu tại i = 1

    for t in range(n_steps):
        # Đề xuất trạng thái mới
        if x == 1:
            x_prop = np.random.choice([1, 2])   # 50% self-loop, 50% đi đến 2
        else:
            x_prop = x + np.random.choice([-1, 1])  # trái hoặc phải

        # Proposal đối xứng → chỉ cần tỷ số mật độ
        log_accept = np.log(pi_unnorm(x_prop, s)) \
                     - np.log(pi_unnorm(x, s))

        # Chấp nhận / từ chối
        if np.log(np.random.uniform()) < log_accept:
            x        = x_prop
            accepted += 1

        chain[t] = x

    return chain, accepted / n_steps



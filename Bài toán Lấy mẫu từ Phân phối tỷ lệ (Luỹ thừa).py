# PHẦN MỞ RỘNG (LIÊN TỤC)

def log_pareto(x, alpha=2.5, x_min=1.0):
    """Log-mật độ Pareto liên tục (không cần hằng số chuẩn hóa)."""
    if x < x_min:
        return -np.inf
    return -alpha * np.log(x)

def pareto_pdf(x, alpha=2.5, x_min=1.0):
    x = np.asarray(x, dtype=float)
    out = np.zeros_like(x)
    m = x >= x_min
    out[m] = (alpha - 1) / x_min * (x[m] / x_min) ** (-alpha)
    return out

def mh_continuous_pareto(n_steps, alpha=2.5, x_min=1.0,
                          proposal_std=0.8, seed=99):
    """
    MH với Log-Normal Random Walk Proposal cho Pareto liên tục.
    Đề xuất: x' = x * exp(ε),  ε ~ N(0, σ²)
    Có Hastings correction (Jacobian): log A += log(x') - log(x)
    """
    np.random.seed(seed)
    samples  = np.zeros(n_steps)
    accepted = 0
    x        = x_min + 0.1

    for t in range(n_steps):
        x_prop    = x * np.exp(np.random.normal(0, proposal_std))
        log_ratio = (log_pareto(x_prop, alpha, x_min)
                     - log_pareto(x, alpha, x_min)
                     + np.log(x_prop) - np.log(x))
        if np.log(np.random.uniform()) < log_ratio:
            x        = x_prop
            accepted += 1
        samples[t] = x

    return samples, accepted / n_steps

ALPHA     = 2.5
N_CONT    = 100_000
BURN_CONT = 10_000

print(f"\n PHẦN MỞ RỘNG — PARETO LIÊN TỤC (Log-Normal Proposal)")
